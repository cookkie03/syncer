#!/usr/bin/env python3
"""Verify a completed Notion export's hashes, inventories and local links offline."""
import argparse
import csv
import hashlib
import json
import re
from pathlib import Path
from urllib.parse import unquote


def verify(backup_root):
    current = (backup_root / 'current').resolve(strict=True)
    if not (current / 'COMPLETE').is_file():
        raise RuntimeError('No COMPLETE marker')
    manifest = json.loads((current / 'manifest.json').read_text())
    if manifest.get('status') not in {'complete', 'complete_with_warnings'}:
        raise RuntimeError('Manifest is incomplete')
    allowed_original = set()
    for item in manifest.get('unresolved_source_links', []):
        oid, ref = item['page_id'], item['url']
        original = json.loads((current / 'json' / oid / 'markdown.json').read_text())['markdown']
        if ref not in original:
            raise RuntimeError('Unresolved reference has no original source evidence')
        allowed_original.add((str(Path(manifest['objects'][oid]['path']) / 'page.md'), ref))
    def local_file(base, url, source_file=None):
        if source_file is not None and (str(source_file.relative_to(current)), url) in allowed_original:
            return
        # Source-authored links can include malformed wrappers such as [https://...].
        # They are external references, not files generated by the exporter.
        if re.match(r'^\[*[A-Za-z][A-Za-z0-9+.-]*:', url) or url.startswith(('#', '//')):
            return
        target = (base / unquote(url.split('#', 1)[0])).resolve()
        if not target.is_relative_to(current) or not target.is_file():
            raise RuntimeError('Broken or out-of-snapshot local reference')
    for name, entry in manifest['files'].items():
        path = (current / name).resolve()
        if not path.is_relative_to(current) or not path.is_file():
            raise RuntimeError('Missing or unsafe manifest file')
        digest = hashlib.sha256()
        with path.open('rb') as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b''):
                digest.update(chunk)
        if digest.hexdigest() != entry['sha256'] or path.stat().st_size != entry['bytes']:
            raise RuntimeError('Checksum or size mismatch')
        if path.suffix == '.md':
            text = path.read_text()
            text = re.sub(r'```[\s\S]*?```', '', text)
            text = re.sub(r'`[^`]*`', '', text)
            refs = re.findall(r'\[[^\]]*\]\(([^\)]+)\)', text)
            refs += re.findall(r'(?:src|url|href)="([^"]+)"', text)
            for ref in refs:
                local_file(path.parent, ref, path)
    pages = sources = databases = rows = 0
    for oid, item in manifest['objects'].items():
        obj = json.loads((current / 'json' / oid / 'content.json').read_text())
        if obj['id'] != oid:
            raise RuntimeError('Object ID mismatch')
        base = current / item['path']
        if item['type'] == 'page':
            pages += 1
            if not (base / 'page.md').is_file():
                raise RuntimeError('Page Markdown missing')
        if item['type'] == 'database':
            databases += 1
        if item['type'] == 'data_source':
            sources += 1
            stored = json.loads((current / 'json' / oid / 'rows.json').read_text())
            with (base / 'rows.csv').open(newline='') as stream:
                actual = list(csv.DictReader(stream))
            if len(actual) != len(stored) or {r['_notion_page_id'] for r in actual} != {r['id'] for r in stored}:
                raise RuntimeError('CSV and JSON row inventories disagree')
            for row in actual:
                local_file(base, row['_local_page'])
            rows += len(actual)
    return {'pages': pages, 'databases': databases, 'data_sources': sources, 'rows': rows,
            'files_verified': len(manifest['files']),
            'assets': sum(name.startswith('assets/') for name in manifest['files']),
            'warnings': len(manifest['warnings']), 'unresolved_source_links': len(allowed_original), 'status': manifest['status']}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--backup-dir', type=Path, default=Path('/private/tmp/syncer-notion-test/backup'))
    args = parser.parse_args()
    print(json.dumps(verify(args.backup_dir), indent=2))
